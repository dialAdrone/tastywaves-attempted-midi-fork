"""Constant tables of the v1 engine (firmware/src/synth.h): everything that needs exp/tan/tanh, computed here so the
firmware stays integer only. Writes firmware/gen/engine_tables.h (const, flash only).

    .venv/bin/python tools/gen_engine_tables.py

CR (frames per control step) must match ENG_CR in firmware/src/synth.h.
"""
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FS = 44100
CR = 32                       # control rate: one step per 32 frames (0.726 ms)
Q30 = 1 << 30
Q28 = 1 << 28


def note_hz(n):
    return 440.0 * 2.0 ** ((n - 69) / 12.0)


def env_time(p):              # 0..127 -> 0.5 ms .. 10 s, exponential
    return 0.0005 * (20000.0 ** (p / 127.0))


def tables():
    t = {}
    # pitch: fraction of a semitone in 1/256 steps -> (2^(i/3072) - 1) * 65536
    t['FINE16'] = ('uint16_t', [round((2.0 ** (i / 3072.0) - 1.0) * 65536) for i in range(256)],
                   'fraction of a semitone (i / 256) -> (ratio - 1) * 65536')
    # SVF: g = tan(pi f / fs), Q28, per semitone (MIDI note numbers 0..135); capped at 18 kHz
    g = []
    for n in range(136):
        f = min(note_hz(n), 18000.0)
        g.append(round(math.tan(math.pi * f / FS) * Q28))
    t['SVF_G'] = ('int32_t', g, 'note number 0..135 -> g = tan(pi f / fs), Q28 (cutoff capped at 18 kHz)')
    # resonance: 0..127 -> 2R, Q28; R from 0.707 (flat) down to 0.015 (close to self-oscillation)
    t['SVF_2R'] = ('int32_t', [round(2 * 0.707 * ((0.015 / 0.707) ** (r / 127.0)) * Q28) for r in range(128)],
                   'resonance 0..127 -> 2R (damping), Q28: R = 0.707 .. 0.015')
    # envelopes: linear step for a full-scale traverse in T, and exponential coefficient for -60 dB in T, per CR
    t['ENV_STEP'] = ('int32_t', [min(Q30, max(1, round(Q30 * CR / (env_time(p) * FS)))) for p in range(128)],
                     'time 0..127 (0.5 ms .. 10 s) -> Q30 step per control step for a full-scale ramp')
    t['ENV_COEF'] = ('int32_t', [round(Q30 * 10.0 ** (-3.0 * CR / (env_time(p) * FS))) for p in range(128)],
                     'time 0..127 -> Q30 multiplier per control step, -60 dB after the time')
    # glide: 0 = off, 1..127 -> 5 ms .. 5 s to ~98 %; one-pole coefficient per CR, Q16
    gl = [65536]
    for p in range(1, 128):
        T = 0.005 * (1000.0 ** ((p - 1) / 126.0))
        gl.append(max(1, round(65536 * (1.0 - math.exp(-CR * 4.0 / (T * FS))))))
    t['GLIDE_K'] = ('int32_t', gl, 'glide 0..127 -> one-pole coefficient per control step, Q16 (0 = instant)')
    # LFO: 0..127 -> 0.02 .. 40 Hz; phase step per control step (2^32 = a cycle)
    t['LFO_INC'] = ('uint32_t', [round(0.02 * (2000.0 ** (p / 127.0)) * 2 ** 32 * CR / FS) for p in range(128)],
                    'LFO rate 0..127 (0.02 .. 40 Hz) -> phase step per control step')
    # drive: 0..127 -> gain 1 .. 16, Q8
    t['DRIVE_G'] = ('int32_t', [round(256 * 16.0 ** (p / 127.0)) for p in range(128)], 'drive 0..127 -> gain 1..16, Q8')
    # soft clip above the knee (16384): u = |x| - 16384 in 0 .. 4 FS, 512 per step: 16383 * tanh(u / 16384)
    t['SOFTCLIP'] = ('int16_t', [round(16383 * math.tanh(i * 512 / 16384.0)) for i in range(258)],
                     'soft clip above the knee: (|x| - 16384) / 512 -> 16383 tanh(u / 16384), + 1 guard')
    # sine, 256 steps + 1 guard, Q15: the BEND warp (linear interpolation between entries)
    t['SIN_T'] = ('int16_t', [round(32767 * math.sin(2 * math.pi * i / 256)) for i in range(257)],
                  'sine, a cycle in 256 steps + 1 guard, Q15 (BEND)')
    # Catmull-Rom as a 4-tap polyphase FIR (eco read): taps for samples i-1..i+2 at fraction j / 256, Q15
    cr = []
    for j in range(256):
        u = j / 256
        w = [(-u**3 + 2*u**2 - u) / 2, (3*u**3 - 5*u**2 + 2) / 2, (-3*u**3 + 4*u**2 + u) / 2, (u**3 - u**2) / 2]
        q = [round(v * 32768) for v in w]
        q[1] += 32768 - sum(q)
        q[1] = min(q[1], 32767)
        cr += q
    t['CR4_TAPS'] = ('int16_t', cr, 'Catmull-Rom, 256 phases x 4 taps (samples i-1 .. i+2), Q15 (eco read)')
    # level hysteresis (dark side): go down from level L only when inc < 2^(24 + L) * 2^(-1/4)
    t['HYST_DN'] = ('uint32_t', [0] + [round(2 ** (24 + L) * 2 ** -0.25) for L in range(1, 7)],
                    'mip level L -> inc below which level L - 1 is used again (1/4 octave under its ceiling)')
    return t


def main():
    lines = ['/* generated by tools/gen_engine_tables.py. Do not edit. */',
             '/* SPDX-License-Identifier: GPL-3.0-only */',
             '#pragma once',
             '#include <stdint.h>',
             '',
             f'#define ENG_TABLES_CR {CR}u            /* the control step these tables assume (frames) */',
             '']
    for name, (ty, vals, doc) in tables().items():
        lines.append(f'/* {doc} */')
        lines.append(f'static const {ty} {name}[{len(vals)}] = {{')
        for i in range(0, len(vals), 12):
            lines.append('    ' + ', '.join(f'{v}' + ('u' if ty.startswith('uint') and v > 0x7FFFFFFF else '')
                                            for v in vals[i:i + 12]) + ',')
        lines.append('};')
        lines.append('')
    out = ROOT / 'firmware' / 'gen' / 'engine_tables.h'
    out.write_text('\n'.join(lines))
    print(f'{out.relative_to(ROOT)}: {sum(len(v[1]) for v in tables().values())} entries')
    return 0


if __name__ == '__main__':
    sys.exit(main())
