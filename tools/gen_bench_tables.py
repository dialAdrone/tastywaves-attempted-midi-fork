"""Guarded wavetables + 8-tap sinc taps for the oscillator CPU bench (firmware/src/wtbench.h, BENCH build).

The factory header (firmware/gen/wavetables.h, tools/gen_wavetables.py) stores each mip level as [N][1 guard]:
enough for linear interpolation only. Catmull-Rom reads samples i-1..i+2 and the 8-tap sinc i-3..i+4, so this tool
re-lays the same int16 data (parsed from wavetables.h, bit-exact) as [3 pre][N][4 post] per level (the layout
recommended in docs/research/wavetable-spectrum.md). The levels are periodic, so the guards are wrap copies:
pre = the last 3 samples, post = the first 4. All three interpolators then read without masking.

    firmware/gen/wt_bench.h    WTG_DATA (12 x 32 frames x 557 int16 = 427,776 B), WTG_LEVEL_OFF, WTG_NAME
                               (used by the bench and by the v1 engine, firmware/src/synth.h)

Level 6 (4 samples) is added here: the fundamental of level 0 alone, for notes above fs/4 (inc >= 2^30), where
level 5's second harmonic would alias (docs/research/wavetable-spectrum.md, problem 1).
    firmware/gen/sinc8_taps.h  SINC8_TAPS[256][8] Q15 (4 KiB): Kaiser(beta 6) windowed sinc, taps at -3..+4,
                               each phase sums to 32768, phase 0 to 32767 (the model of tests/wavetable_spectrum.py, C2)

    .venv/bin/python tools/gen_bench_tables.py
"""
import re
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'firmware' / 'gen' / 'wavetables.h'
LEVELS_IN, FRAMES = 6, 32
LEVELS = LEVELS_IN + 1                                   # + level 6: 4 samples, the fundamental only (f0 > fs/4)
LEN = [256 >> L for L in range(LEVELS)]
OFF_IN = [sum(n + 1 for n in LEN[:L]) for L in range(LEVELS_IN)]
FLEN_IN = OFF_IN[-1] + LEN[LEVELS_IN - 1] + 1            # 510
PRE, POST = 3, 4
OFF = [sum(n + PRE + POST for n in LEN[:L]) for L in range(LEVELS)]
FLEN = OFF[-1] + LEN[-1] + PRE + POST                    # 557
PHASES = 256
BETA = 6.0


def parse():
    t = SRC.read_text()
    body = re.search(r'WT_DATA\[\d+\]\s*=\s*\{(.*?)\};', t, re.S).group(1)
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    data = np.array([int(x) for x in body.replace('\n', ' ').split(',') if x.strip()], dtype=np.int32)
    names = re.findall(r'\{"(\w+)", (\d+), (\d+)\}', t)
    assert int(re.search(r'WT_FRAME_LEN\s+(\d+)u', t).group(1)) == FLEN_IN
    assert len(data) == len(names) * FRAMES * FLEN_IN, len(data)
    return data, [n for n, _, _ in names]


def relayout(data, ntab):
    fr = data.reshape(ntab * FRAMES, FLEN_IN)
    out = np.zeros((ntab * FRAMES, FLEN), dtype=np.int32)
    for L, n in enumerate(LEN):
        if L < LEVELS_IN:
            lv = fr[:, OFF_IN[L]:OFF_IN[L] + n]
            assert np.array_equal(fr[:, OFF_IN[L] + n], lv[:, 0])      # the old guard is sample 0
        else:                                                          # fundamental of level 0, 4 samples
            h1 = np.fft.rfft(fr[:, OFF_IN[0]:OFF_IN[0] + 256].astype(np.float64), axis=1)[:, 1] * (2 / 256)
            lv = np.round(np.real(h1[:, None] * np.exp(2j * np.pi * np.arange(n)[None, :] / n))).astype(np.int32)
        out[:, OFF[L]:OFF[L] + PRE + n + POST] = np.concatenate([np.tile(lv, 2)[:, 2 * n - PRE:], lv,
                                                                 np.tile(lv, 2)[:, :POST]], axis=1)
    return out.reshape(-1)


def taps():
    u = np.arange(PHASES)[:, None] / PHASES
    d = u - np.arange(-3, 5)[None, :]
    w = np.sinc(d) * np.i0(BETA * np.sqrt(np.clip(1 - (d / 4) ** 2, 0, None))) / np.i0(BETA)
    w = w / w.sum(axis=1, keepdims=True)
    q = np.round(w * 32768).astype(np.int64)
    q[:, 3] += 32768 - q.sum(axis=1)
    q = np.minimum(q, 32767)                  # phase 0 is the identity (32768 at the centre): int16 holds 32767
    assert q.max() <= 32767 and q.min() >= -32768
    return q


def main():
    data, names = parse()
    g = relayout(data, len(names))
    lines = [
        '/* generated by tools/gen_bench_tables.py from firmware/gen/wavetables.h (same samples, bit-exact). Do not edit.',
        f' * Per frame: {LEVELS} mip levels, level L = [{PRE} pre guards][256 >> L samples][{POST} post guards] (wrap copies),',
        ' * so linear (i, i+1), Catmull-Rom (i-1..i+2) and the 8-tap sinc (i-3..i+4) read without masking.',
        ' * Level 6 (4 samples) holds the fundamental only (notes above fs/4).',
        ' * Sample i of level L of frame f of table t: WTG_DATA[(t * WTG_FRAMES + f) * WTG_FRAME_LEN + WTG_LEVEL_OFF[L] + 3 + i] */',
        '/* SPDX-License-Identifier: GPL-3.0-only */',
        '#pragma once',
        '#include <stdint.h>',
        '',
        f'#define WTG_TABLES    {len(names)}u',
        f'#define WTG_FRAMES    {FRAMES}u',
        f'#define WTG_LEVELS    {LEVELS}u',
        f'#define WTG_PRE       {PRE}u',
        f'#define WTG_FRAME_LEN {FLEN}u',
        f'#define WTG_DATA_LEN  {len(g)}u   /* {len(g) * 2} bytes */',
        '',
        f'static const uint16_t WTG_LEVEL_OFF[{LEVELS}] = {{{", ".join(str(o) for o in OFF)}}};',
        f'static const char WTG_NAME[{len(names)}][6] = {{{", ".join(chr(34) + n + chr(34) for n in names)}}};',
        '',
        f'static const int16_t WTG_DATA[{len(g)}] = {{',
    ]
    for i in range(0, len(g), 24):
        lines.append('    ' + ','.join(str(int(v)) for v in g[i:i + 24]) + ',')
    lines.append('};')
    (ROOT / 'firmware' / 'gen' / 'wt_bench.h').write_text('\n'.join(lines) + '\n')

    q = taps()
    tl = [
        '/* generated by tools/gen_bench_tables.py. Do not edit.',
        f' * 8-tap Kaiser(beta {BETA:g}) windowed sinc, {PHASES} phases, Q15, taps for samples i-3 .. i+4 at fraction',
        f' * phase / {PHASES}; every phase sums to 32768 (unity DC gain), except phase 0 (the identity: 32767). */',
        '/* SPDX-License-Identifier: GPL-3.0-only */',
        '#pragma once',
        '#include <stdint.h>',
        '',
        f'#define SINC8_PHASES {PHASES}u',
        f'static const int16_t SINC8_TAPS[{PHASES} * 8] = {{',
    ]
    for p in range(PHASES):
        tl.append('    ' + ', '.join(str(int(v)) for v in q[p]) + ',')
    tl.append('};')
    (ROOT / 'firmware' / 'gen' / 'sinc8_taps.h').write_text('\n'.join(tl) + '\n')
    print(f'wt_bench.h: {len(names)} tables, frame {FLEN} int16, offsets {OFF}, {len(g) * 2} B; '
          f'max |sample| {int(np.abs(g).max())}, max |step| {int(np.abs(np.diff(g)).max())} (incl. level seams)')
    print(f'sinc8_taps.h: {PHASES} x 8 Q15, sum |taps| max {int(np.abs(q).sum(axis=1).max())}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
